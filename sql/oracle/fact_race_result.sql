DROP TABLE fact_race_result CASCADE CONSTRAINTS;

CREATE TABLE fact_race_result (
    race_result_sk NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_sk NUMBER NOT NULL,
    driver_sk NUMBER NOT NULL,
    constructor_sk NUMBER NOT NULL,
    grid_position NUMBER,
    finish_position NUMBER,
    position_text VARCHAR2(20),
    position_order NUMBER,
    points NUMBER(10,2),
    laps NUMBER,
    status VARCHAR2(100),
    time_millis NUMBER,
    time_text VARCHAR2(50),
    fastest_lap_rank NUMBER,
    fastest_lap_number NUMBER,
    fastest_lap_time VARCHAR2(50),
    fastest_lap_avg_speed NUMBER(10,3),
    fastest_lap_avg_speed_unit VARCHAR2(20),

    CONSTRAINT fk_fact_result_race
        FOREIGN KEY (race_sk) REFERENCES dim_race(race_sk),

    CONSTRAINT fk_fact_result_driver
        FOREIGN KEY (driver_sk) REFERENCES dim_driver(driver_sk),

    CONSTRAINT fk_fact_result_constructor
        FOREIGN KEY (constructor_sk) REFERENCES dim_constructor(constructor_sk),

    CONSTRAINT uk_fact_result_race_driver UNIQUE (race_sk, driver_sk)
);